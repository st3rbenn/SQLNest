/**
 * Adapter Prisma (ADR-037 D3, D4) : migration
 * `migrations/<horodatage>_<…>/migration.sql`, patch du modèle (D6),
 * `prisma format` et `validate`, `migrate deploy`, et `migrate resolve
 * --rolled-back` après un échec. Contrôles : modèle ↔ base, et historique ↔
 * modèle sur une base shadow créée pour l'occasion sur le serveur de la
 * connexion. Sous MongoDB, Prisma ne tient pas d'historique (`db push`) :
 * modèle patché et validé, DDL appliqué par SQLNest, contrôle modèle ↔ base
 * (D3 bis).
 */

import { randomBytes } from "node:crypto";
import {
	cpSync,
	existsSync,
	mkdirSync,
	mkdtempSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync
} from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";
import type { TunnelSchemaCheck } from "@sqlnest/tunnel-protocol";
import {
	connectionIdentity,
	type DbEngine,
	ENGINE_LABELS,
	parseConnectionString,
	withDatabase
} from "../../services/connection-strings";
import {
	type OrmAdapter,
	type SchemaChange,
	SchemaChangeError
} from "../adapter";
import { detectOrms } from "../detect";
import { patchPrismaSchema } from "./patch";
import {
	datasourceEnvKeys,
	datasourceProvider,
	joinSchemaFiles,
	migrationName,
	type PrismaSchemaLocation,
	prismaDatabaseUrl,
	prismaSchemaLocation,
	splitSchemaFiles
} from "./project";
import {
	findPrismaBinary,
	runTool,
	type ToolRun,
	toolMessage,
	toolScript
} from "./tool";

const TIMEOUT_MS = 120_000;
/** Fournisseur Prisma de chaque moteur. */
const PROVIDERS: Readonly<Record<string, string>> = {
	postgres: "postgresql",
	mssql: "sqlserver",
	mongodb: "mongodb"
};
/** Moteurs où Prisma ne tient pas d'historique de migrations (`db push`). */
const WITHOUT_HISTORY = new Set(["mongodb"]);
/** Fournisseur écrit par Prisma dans `migration_lock.toml` (son nom interne). */
const LOCK_PROVIDERS: Readonly<Record<string, string>> = {
	postgres: "postgresql",
	mssql: "mssql"
};
const MIGRATION_LOCK = (provider: string): string =>
	`# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "${provider}"\n`;
const LOCK_PROVIDER_RE = /provider\s*=\s*"[^"]*"/;
/** `migrate resolve` sur une migration que `deploy` n'a jamais enregistrée. */
const NEVER_APPLIED = "P3011";

interface PrismaProject {
	readonly dir: string;
	readonly bin: string;
	readonly schema: PrismaSchemaLocation;
	/** Fournisseur du `datasource`. */
	readonly provider: string;
	/** Fournisseur du verrou de migrations. */
	readonly lockProvider: string;
	/** Prisma tient l'historique des migrations de ce moteur (pas sous MongoDB). */
	readonly history: boolean;
	/** Environnement de l'outil : les variables du `datasource` visent la base de la connexion. */
	readonly env: NodeJS.ProcessEnv;
}

const resolved = new WeakMap<SchemaChange, PrismaProject>();

export const prismaAdapter: OrmAdapter = {
	orm: "prisma",
	ddlOptions: () => ({ ormProfile: "prisma" }),
	migrations: (engine) => !WITHOUT_HISTORY.has(engine),

	async preflight(change) {
		const project = prismaProject(change);
		if (!change.project.apply || !project.history) return;
		const status = await prisma(project, ["migrate", "status"]);
		if (status.code !== 0) {
			throw new SchemaChangeError(toolMessage(status, project.dir));
		}
	},

	async writeMigration(change) {
		const project = prismaProject(change);
		const dir = project.schema.migrations;
		const createdDir = !existsSync(dir);
		mkdirSync(dir, { recursive: true });
		const lock = join(dir, "migration_lock.toml");
		const createdLock = !existsSync(lock);
		if (createdLock) writeFileSync(lock, MIGRATION_LOCK(project.lockProvider));
		const existing = readdirSync(dir, { withFileTypes: true })
			.filter((e) => e.isDirectory())
			.map((e) => e.name);
		const name = migrationName(change.plan, existing, new Date());
		const folder = join(dir, name);
		mkdirSync(folder);
		const file = join(folder, "migration.sql");
		writeFileSync(file, change.sql ?? "");
		return {
			name,
			files: [
				relative(project.dir, file),
				...(createdLock ? [relative(project.dir, lock)] : [])
			],
			undo: () => {
				rmSync(folder, { recursive: true, force: true });
				if (createdLock) rmSync(lock, { force: true });
				if (createdDir) rmSync(dir, { recursive: true, force: true });
			}
		};
	},

	async patchModel(change) {
		const project = prismaProject(change);
		const originals = project.schema.files.map((path) => ({
			path,
			text: readFileSync(path, "utf8")
		}));
		const rel = (path: string): string => relative(project.dir, path);
		const patch = patchPrismaSchema(
			joinSchemaFiles(
				originals.map((f) => ({ path: rel(f.path), text: f.text }))
			),
			change.plan,
			{
				schema: change.before,
				...(change.names !== undefined ? { names: change.names } : {})
			}
		);
		const texts = splitSchemaFiles(
			patch.text,
			originals.map((f) => rel(f.path))
		);
		for (const f of originals) {
			const text = texts.get(rel(f.path));
			if (text !== undefined && text !== f.text) writeFileSync(f.path, text);
		}
		const named =
			patch.names.model !== undefined || patch.names.relations !== undefined;
		return {
			// Après `prisma format`, qui peut toucher d'autres fichiers du schéma.
			get files() {
				return originals
					.filter((f) => readFileSync(f.path, "utf8") !== f.text)
					.map((f) => rel(f.path));
			},
			...(named ? { names: patch.names } : {}),
			undo: () => {
				for (const f of originals) writeFileSync(f.path, f.text);
			}
		};
	},

	async validate(change) {
		const project = prismaProject(change);
		for (const command of ["format", "validate"]) {
			const run = await prisma(project, [command]);
			if (run.code !== 0) {
				throw new SchemaChangeError(toolMessage(run, project.dir));
			}
		}
	},

	async apply(change) {
		const project = prismaProject(change);
		const run = await prisma(project, ["migrate", "deploy"]);
		if (run.code !== 0) {
			throw new SchemaChangeError(toolMessage(run, project.dir));
		}
	},

	async rollback(change, migration) {
		const project = prismaProject(change);
		const run = await prisma(project, [
			"migrate",
			"resolve",
			"--rolled-back",
			migration.name
		]);
		if (
			run.code !== 0 &&
			!`${run.stdout}${run.stderr}`.includes(NEVER_APPLIED)
		) {
			throw new SchemaChangeError(toolMessage(run, project.dir));
		}
	},

	async check(change, _migration, applied) {
		const project = prismaProject(change);
		// Sous MongoDB, `migrate diff` compare collections et index, sans `--script`.
		const modelDatabase: TunnelSchemaCheck = applied
			? diffCheck(
					"model-database",
					await prismaDiff(project, [
						"--from-schema-datasource",
						project.schema.arg,
						"--to-schema-datamodel",
						project.schema.arg,
						...(project.history ? ["--script"] : []),
						"--exit-code"
					]),
					project
				)
			: { name: "model-database", skipped: "base non touchée (apply = false)" };
		return [
			modelDatabase,
			project.history
				? await historyCheck(change, project)
				: {
						name: "history-model",
						skipped:
							"pas d'historique de migrations Prisma sous MongoDB (db push)"
					}
		];
	}
};

/** Projet relié, résolu une fois par changement. */
function prismaProject(change: SchemaChange): PrismaProject {
	const known = resolved.get(change);
	if (known !== undefined) return known;
	const dir = change.project.path;
	const detection = detectOrms(dir).find((d) => d.orm === "prisma");
	const schema =
		detection !== undefined ? prismaSchemaLocation(detection) : undefined;
	if (detection === undefined || schema === undefined) {
		throw new SchemaChangeError(
			"Le projet relié n'est plus un projet Prisma : schéma introuvable"
		);
	}
	const bin = findPrismaBinary(dir);
	if (bin === undefined) {
		throw new SchemaChangeError(
			"Prisma n'est pas installé dans le projet relié (npm install)"
		);
	}
	const engine = change.before.engine;
	const label = ENGINE_LABELS[engine as DbEngine] ?? engine;
	const expected = PROVIDERS[engine];
	if (expected === undefined) {
		throw new SchemaChangeError(`Prisma ne connaît pas le moteur ${label}`);
	}
	const datasource = readFileSync(schema.datasourceFile, "utf8");
	const provider = datasourceProvider(datasource);
	if (provider !== expected) {
		throw new SchemaChangeError(
			`Le schéma Prisma décrit une base « ${provider ?? "?"} », la connexion est ${label}`
		);
	}
	const connection = parseConnectionString(change.databaseUrl);
	if (connection === undefined) {
		throw new SchemaChangeError("URL de la connexion illisible");
	}
	const keys = [
		...datasourceEnvKeys(datasource),
		...(detection.envKey !== undefined ? [detection.envKey] : [])
	];
	if (keys.length === 0 && detection.url !== undefined) {
		// URL écrite dans le schéma : Prisma la lit telle quelle.
		const written = parseConnectionString(detection.url);
		if (
			written === undefined ||
			connectionIdentity(written) !== connectionIdentity(connection)
		) {
			throw new SchemaChangeError(
				"Le schéma Prisma vise une autre base que la connexion reliée"
			);
		}
	}
	const url = prismaDatabaseUrl(connection);
	const project: PrismaProject = {
		dir,
		bin,
		schema,
		provider: expected,
		lockProvider: LOCK_PROVIDERS[engine] ?? expected,
		history: !WITHOUT_HISTORY.has(engine),
		env: {
			...change.env,
			...Object.fromEntries(keys.map((key) => [key, url])),
			PRISMA_HIDE_UPDATE_MESSAGE: "1",
			NO_COLOR: "1"
		}
	};
	resolved.set(change, project);
	return project;
}

/** Commande `prisma` du projet, sur son schéma. */
function prisma(
	project: PrismaProject,
	args: readonly string[]
): Promise<ToolRun> {
	return runTool(project.bin, [...args, "--schema", project.schema.arg], {
		cwd: project.dir,
		env: project.env,
		timeoutMs: TIMEOUT_MS
	});
}

/** `prisma migrate diff …` : ses sources et cibles désignent le schéma (pas de `--schema`). */
function prismaDiff(
	project: PrismaProject,
	args: readonly string[]
): Promise<ToolRun> {
	return runTool(project.bin, ["migrate", "diff", ...args], {
		cwd: project.dir,
		env: project.env,
		timeoutMs: TIMEOUT_MS
	});
}

/** `migrate diff --exit-code` : 0 conforme, 2 écart (le SQL qui le comblerait). */
function diffCheck(
	name: TunnelSchemaCheck["name"],
	run: ToolRun,
	project: PrismaProject
): TunnelSchemaCheck {
	if (run.code === 0) return { name, ok: true };
	if (run.code === 2) return { name, ok: false, diff: toolScript(run) };
	return { name, skipped: toolMessage(run, project.dir) };
}

/**
 * Historique des migrations rejoué sur une base shadow, comparé au modèle.
 * Prisma écrit `mssql` dans le verrou d'un projet SQL Server, mais `migrate
 * diff --from-migrations` n'y connaît que `sqlserver` : le contrôle lit une
 * copie des migrations dont le verrou porte le fournisseur du `datasource`.
 */
async function historyCheck(
	change: SchemaChange,
	project: PrismaProject
): Promise<TunnelSchemaCheck> {
	let shadow: { readonly url: string; drop(): Promise<void> };
	try {
		shadow = await createShadowDatabase(change);
	} catch (err) {
		return {
			name: "history-model",
			skipped: `base shadow impossible à créer : ${err instanceof Error ? err.message : String(err)}`
		};
	}
	const migrations = mkdtempSync(join(tmpdir(), "sqlnest-migrations-"));
	try {
		cpSync(project.schema.migrations, migrations, { recursive: true });
		const lock = join(migrations, "migration_lock.toml");
		if (existsSync(lock)) {
			writeFileSync(
				lock,
				readFileSync(lock, "utf8").replace(
					LOCK_PROVIDER_RE,
					`provider = "${project.provider}"`
				)
			);
		}
		const run = await prismaDiff(project, [
			"--from-migrations",
			migrations,
			"--to-schema-datamodel",
			project.schema.arg,
			"--shadow-database-url",
			shadow.url,
			"--script",
			"--exit-code"
		]);
		return diffCheck("history-model", run, project);
	} finally {
		rmSync(migrations, { recursive: true, force: true });
		await shadow.drop();
	}
}

/** Base vide sur le serveur de la connexion, retirée après le contrôle. */
async function createShadowDatabase(
	change: SchemaChange
): Promise<{ readonly url: string; drop(): Promise<void> }> {
	const connection = parseConnectionString(change.databaseUrl);
	if (connection === undefined)
		throw new Error("URL de la connexion illisible");
	const name = `sqlnest_shadow_${Date.now().toString(36)}${randomBytes(3).toString("hex")}`;
	const conn = change.connection;
	const run = (text: string) =>
		conn.execute({
			engine: conn.engine,
			kind: "sql",
			text,
			params: [],
			paramSpans: []
		});
	if (conn.engine === "mssql") {
		await run(`CREATE DATABASE [${name}]`);
		return {
			url: prismaDatabaseUrl(withDatabase(connection, name)),
			drop: async () => {
				await run(
					`ALTER DATABASE [${name}] SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE [${name}];`
				).catch(() => undefined);
			}
		};
	}
	await run(`CREATE DATABASE "${name}"`);
	return {
		url: prismaDatabaseUrl(withDatabase(connection, name)),
		drop: async () => {
			await run(`DROP DATABASE IF EXISTS "${name}" WITH (FORCE)`).catch(() =>
				run(`DROP DATABASE IF EXISTS "${name}"`).catch(() => undefined)
			);
		}
	};
}
